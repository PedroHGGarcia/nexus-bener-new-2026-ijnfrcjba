/** Retorna a lista de cidades de uma UF ou array vazio */
export function getCidadesPorUf(uf: string | null | undefined): string[] {
  if (!uf) return []
  const norm = uf.trim().toUpperCase()
  return CIDADES_POR_UF[norm] || []
}

/**
 * Normaliza uma string para comparação sem acentos e caixa baixa.
 */
export function normalizeSearchTerm(str: string): string {
  return str
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .trim()
}
